"""Generate the 20/28/40 px, 4 bpp MyBot UI fonts with Pillow/FreeType.

The input is the pinned OFL-licensed NotoSansSC.ttf documented in VENDORED_SOURCES.md.
Only printable ASCII and the Chinese characters used by the view are embedded.
Usage: python3 scripts/generate-lvgl-font.py --font path/to/NotoSansSC.ttf
"""

import argparse
import hashlib
import subprocess
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version, features


FONT_SHA256 = "a0af66489baf1f306732ff16da58d86c342e0b3b4b3674079ee2a9b0aee23258"
ROOT = Path(__file__).resolve().parent.parent
VIEW = ROOT / "components/mybot_platform/src/drivers/display/renderers/lvgl/lvgl_view.cc"
OUTPUT = ROOT / "components/mybot_platform/src/drivers/display/renderers/lvgl/lvgl_fonts.c"


def rows(values, width=12):
    return "\n".join(
        "    " + ", ".join(values[index : index + width]) + ","
        for index in range(0, len(values), width)
    )


def render_font(font_path, pixels, codepoints):
    font = ImageFont.truetype(str(font_path), pixels)
    missing = bytes(font.getmask("\u0378"))
    bitmap = []
    descriptors = ["    /* Glyph ID 0 is reserved. */\n    {0},"]
    ascent = descent = 0
    for codepoint in codepoints:
        character = chr(codepoint)
        if bytes(font.getmask(character)) == missing:
            raise ValueError(f"Missing glyph U+{codepoint:04X}")
        x0, y0, x1, y1 = font.getbbox(character, anchor="ls")
        width, height = x1 - x0, y1 - y0
        if height == 0:
            width = 0
        advance = round(font.getlength(character) * 16)
        descriptors.append(
            "    /* U+%04X */\n"
            "    { .bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, "
            ".ofs_x = %d, .ofs_y = %d },"
            % (codepoint, len(bitmap), advance, width, height, x0, -y1)
        )
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-x0, -y0), character, font=font, fill=255, anchor="ls")
            coverage_pixels = image.get_flattened_data() if hasattr(image, "get_flattened_data") else image.getdata()
            coverage = [(pixel * 15 + 127) // 255 for pixel in coverage_pixels]
            if len(coverage) % 2:
                coverage.append(0)
            bitmap.extend((coverage[i] << 4) | coverage[i + 1] for i in range(0, len(coverage), 2))
            ascent = max(ascent, -y0)
            descent = max(descent, y1)
    text = f"""/* MyBot UI Sans: {pixels} px, 4 bpp subset of Noto Sans SC Regular.
 * Copyright 2014, 2015 Adobe Systems Incorporated (http://www.adobe.com/).
 * See LVGL_VIEW_FONT_LICENSE.txt. Generated by scripts/generate-lvgl-font.py.
 * Input SHA256: {FONT_SHA256}
 * Pillow {pillow_version}; FreeType {features.version("freetype2")}; {len(codepoints)} glyphs.
 */
#include "lvgl.h"

static const uint8_t glyph_bitmap_{pixels}[] = {{
{rows([f"0x{value:02x}" for value in bitmap])}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc_{pixels}[] = {{
{chr(10).join(descriptors)}
}};

static const uint16_t unicode_list_{pixels}[] = {{
{rows([f"0x{codepoint - 0x20:04x}" for codepoint in codepoints])}
}};

static const lv_font_fmt_txt_cmap_t cmaps_{pixels}[] = {{
    {{
        .range_start = 0x20,
        .range_length = {codepoints[-1] - 0x20 + 1},
        .glyph_id_start = 1,
        .unicode_list = unicode_list_{pixels},
        .list_length = {len(codepoints)},
        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
    }},
}};

static const lv_font_fmt_txt_dsc_t font_dsc_{pixels} = {{
    .glyph_bitmap = glyph_bitmap_{pixels},
    .glyph_dsc = glyph_dsc_{pixels},
    .cmaps = cmaps_{pixels},
    .cmap_num = 1,
    .bpp = 4,
}};

const lv_font_t mybot_lvgl_font_{pixels} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent + 2},
    .base_line = {descent + 1},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc_{pixels},
}};
"""
    return text, len(bitmap)


def generate(font_path):
    if hashlib.sha256(font_path.read_bytes()).hexdigest() != FONT_SHA256:
        raise ValueError("Unexpected font revision; verify its provenance and license first")
    language_source = ROOT / "components/mybot_stack/mybot_sdk/mybot/src/core/mybot_ui.c"
    source = VIEW.read_text() + language_source.read_text()
    codepoints = sorted(set(range(0x20, 0x7F)) | {ord(c) for c in source if ord(c) > 127})
    fonts = [render_font(font_path, pixels, codepoints) for pixels in (20, 28, 40)]
    OUTPUT.write_text("/* SPDX-License-Identifier: OFL-1.1 */\n" + "\n".join(text for text, _ in fonts))
    subprocess.run(["clang-format", "-i", str(OUTPUT)], check=True)
    print(f"Generated {OUTPUT.relative_to(ROOT)}: {len(codepoints)} glyphs per size, "
          f"{sum(size for _, size in fonts)} bitmap bytes across 20/28/40 px")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", required=True, type=Path)
    args = parser.parse_args()
    generate(args.font)
